import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'extensions/theme-seti');
const destination = resolve(root, 'extensions/theme-v3code/fileicons');
const theme = JSON.parse(readFileSync(resolve(source, 'icons/vs-seti-icon-theme.json'), 'utf8'));
const original = structuredClone(theme);
const palette = {
	'#519aba': '#7295a6', '#cc3e44': '#b8797c', '#a074c4': '#9a88ad',
	'#cbcb41': '#aba477', '#8dc149': '#8fa57a', '#4d5a5e': '#81878a',
	'#e37933': '#b68d70', '#6d8086': '#889397', '#d4d7d6': '#909094',
	'#f55385': '#b58196', '#41535b': '#7d8b91',
};
for (const [name, definition] of Object.entries(theme.iconDefinitions)) {
	// Preserve the upstream light palette; accessibility themes use the original colors.
	if (!name.endsWith('_light') && definition.fontColor) {
		definition.fontColor = palette[definition.fontColor] ?? definition.fontColor;
	}
}
theme.information_for_contributors.unshift('V3Code Graphite: generated by scripts/v3-build-graphite-icons.mjs.');
theme.hidesExplorerArrows = false;
theme.highContrast = { file: original.file + '_hc' };
for (const [name, definition] of Object.entries(original.iconDefinitions)) {
	theme.iconDefinitions[name + '_hc'] = definition;
}
for (const field of ['fileExtensions', 'fileNames', 'languageIds']) {
	theme.highContrast[field] = Object.fromEntries(Object.entries(original[field]).map(([key, value]) => [key, value + '_hc']));
}
writeFileSync(resolve(destination, 'vs_graphite-icon-theme.json'), JSON.stringify(theme, null, '\t') + '\n');
copyFileSync(resolve(source, 'icons/seti.woff'), resolve(destination, 'seti.woff'));
writeFileSync(resolve(destination, 'SETI-NOTICES.txt'), readFileSync(resolve(source, 'ThirdPartyNotices.txt'), 'utf8').replaceAll('\r\n', '\n').replaceAll('\u2020', ''));
console.log(`V3Code Graphite: ${Object.keys(theme.iconDefinitions).length} definitions generated.`);
